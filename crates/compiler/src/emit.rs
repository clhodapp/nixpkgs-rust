//! Writing the generated Cargo workspace.
//!
//! ```text
//! <out>/Cargo.toml        the workspace
//! <out>/gen/cNNN/         one crate per chunk of generated functions
//! <out>/program/          the symbol and file tables, and `main`
//! ```

use std::fmt::Write;
use std::fs;
use std::path::Path;

use crate::codegen::Compiler;
use crate::strings::rust_str;

/// One compiled file: its path relative to the root, and the id of the unit
/// evaluating it or the reason it did not compile.
pub struct FileRec {
    pub path: String,
    pub result: Result<u32, String>,
}

/// What to write.
pub struct EmitOpts<'a> {
    pub out: &'a Path,
    /// The runtime crate, as a path the generated manifests can use.
    pub runtime: &'a str,
    /// The root directory the program reads its files from by default.
    pub root: &'a str,
    pub bin_name: &'a str,
    /// The optimisation level of the generated crates in release builds.
    pub opt_level: u8,
}

fn write_if_changed(path: &Path, contents: &str) -> std::io::Result<()> {
    if fs::read_to_string(path).ok().as_deref() == Some(contents) {
        return Ok(());
    }
    if let Some(dir) = path.parent() {
        fs::create_dir_all(dir)?;
    }
    fs::write(path, contents)
}

fn crate_name(i: usize) -> String {
    format!("nixpkgs-rust-gen-{i:04}")
}

/// Writes the workspace.
pub fn emit(c: &Compiler, files: &[FileRec], o: &EmitOpts) -> std::io::Result<()> {
    let ncrates = c.crates.len() - 1;
    let mut members = vec!["\"program\"".to_string()];
    for i in 1..=ncrates {
        members.push(format!("\"gen/c{i:04}\""));
    }
    let workspace = format!(
        r#"# Generated by nixpkgs-rust-compiler.
[workspace]
resolver = "2"
members = [{}]

[profile.dev]
opt-level = 0
debug = false
incremental = false

[profile.dev.package."*"]
opt-level = 2

# The generated crates are many and large: optimising them multiplies the
# build time (about seven times at opt-level 2) and its memory by half again.
[profile.release]
opt-level = {}
debug = false
codegen-units = 16
incremental = false

# Every package outside this workspace: the runtime and its dependencies
# (hashing, regular expressions), where evaluation spends much of its time.
# Naming only the runtime would leave its dependencies unoptimised.
[profile.release.package."*"]
opt-level = 3
codegen-units = 16
"#,
        members.join(", "),
        o.opt_level
    );
    write_if_changed(&o.out.join("Cargo.toml"), &workspace)?;

    for (i, cr) in c.crates.iter().enumerate().skip(1) {
        let dir = o.out.join(format!("gen/c{i:04}"));
        let manifest = format!(
            "[package]\nname = \"{}\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n[lib]\npath = \"lib.rs\"\n\n[dependencies]\nnixpkgs-rust-runtime = {{ path = {} }}\n",
            crate_name(i),
            rust_str(o.runtime)
        );
        write_if_changed(&dir.join("Cargo.toml"), &manifest)?;
        let mut src = String::with_capacity(cr.src.len() + cr.fns.len() * 8 + 256);
        src.push_str("// Generated by nixpkgs-rust-compiler.\n#![allow(unused, non_upper_case_globals, clippy::all)]\nuse nixpkgs_rust_runtime::prelude::*;\n");
        src.push_str(&cr.src);
        src.push_str("pub static TABLES: CrateTables = CrateTables { codes: &[");
        for f in &cr.fns {
            src.push_str(f);
            src.push(',');
        }
        src.push_str("] };\n");
        write_if_changed(&dir.join("lib.rs"), &src)?;
    }

    let mut manifest = format!(
        "[package]\nname = \"nixpkgs-rust-program\"\nversion = \"0.0.0\"\nedition = \"2024\"\npublish = false\n\n[[bin]]\nname = {}\npath = \"src/main.rs\"\n\n[dependencies]\nnixpkgs-rust-runtime = {{ path = {} }}\n",
        rust_str(o.bin_name),
        rust_str(o.runtime)
    );
    for i in 1..=ncrates {
        let _ = writeln!(manifest, "{} = {{ path = \"../gen/c{i:04}\" }}", crate_name(i));
    }
    write_if_changed(&o.out.join("program/Cargo.toml"), &manifest)?;

    let mut lib = String::from(
        "// Generated by nixpkgs-rust-compiler.\n#![allow(clippy::all)]\nuse nixpkgs_rust_runtime::program::{FileEntry, Program};\nuse nixpkgs_rust_runtime::value::{CodeId, CrateTables};\n\nstatic EMPTY: CrateTables = CrateTables { codes: &[] };\n\n",
    );
    let _ = writeln!(lib, "/// The root directory the files were compiled from.\npub const ROOT: &str = {};\n", rust_str(o.root));
    lib.push_str("pub static PROGRAM: Program = Program {\n    symbols: &[");
    for n in &c.syms.names {
        lib.push_str(&rust_str(n));
        lib.push(',');
    }
    lib.push_str("],\n    crates: &[&EMPTY,");
    for i in 1..=ncrates {
        let _ = write!(lib, "&{}::TABLES,", crate_name(i).replace('-', "_"));
    }
    lib.push_str("],\n    files: &[\n");
    for f in files {
        match &f.result {
            Ok(id) => {
                let _ = writeln!(lib, "        FileEntry {{ path: {}, code: Some(CodeId({id})), error: \"\" }},", rust_str(&f.path));
            }
            Err(e) => {
                let _ = writeln!(lib, "        FileEntry {{ path: {}, code: None, error: {} }},", rust_str(&f.path), rust_str(e));
            }
        }
    }
    lib.push_str("    ],\n};\n");
    write_if_changed(&o.out.join("program/src/lib.rs"), &lib)?;
    write_if_changed(
        &o.out.join("program/src/main.rs"),
        "// Generated by nixpkgs-rust-compiler.\nfn main() {\n    nixpkgs_rust_runtime::cli::main(&nixpkgs_rust_program::PROGRAM, nixpkgs_rust_program::ROOT)\n}\n",
    )?;
    Ok(())
}
